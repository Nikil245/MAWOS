class TableBlock(StrictAssistantModel):
    type: Literal["table"]
    title: str | None = Field(default=None, max_length=120)
    caption: str = Field(min_length=1, max_length=240)
    columns: list[TableColumn] = Field(min_length=1, max_length=12)
    rows: list[dict[str, CellValue]] = Field(default_factory=list, max_length=100)

    @model_validator(mode="after")
    def rows_match_columns(self):
        keys = [column.key for column in self.columns]
        if len(keys) != len(set(keys)):
            raise ValueError("table column keys must be unique")
        allowed = set(keys)
        if any(set(row) - allowed for row in self.rows):
            raise ValueError("table rows contain undeclared columns")
        return self


