class LinkActionBlock(StrictAssistantModel):
    type: Literal["link_action"]
    label: str = Field(min_length=1, max_length=100)
    url: str = Field(min_length=1, max_length=2048)
    description: str | None = Field(default=None, max_length=240)
    external: bool = False

    @field_validator("url")
    @classmethod
    def safe_link(cls, value: str) -> str:
        import ipaddress
        from urllib.parse import urlsplit

        if any(character.isspace() or ord(character) < 32 for character in value):
            raise ValueError("link contains unsupported characters")
        if value.startswith("/") and not value.startswith("//") and "\\" not in value:
            return value
        parsed = urlsplit(value)
        if (parsed.scheme not in {"http", "https"} or not parsed.hostname
                or parsed.username or parsed.password):
            raise ValueError("link must be an app-relative or HTTP(S) URL without credentials")
        host = parsed.hostname.rstrip(".").lower()
        if host in {"localhost", "localhost.localdomain"} or host.endswith(".local"):
            raise ValueError("link must not target an internal host")
        try:
            address = ipaddress.ip_address(host)
        except ValueError:
            address = None
        if address is not None and not address.is_global:
            raise ValueError("link must not target an internal host")
        return value


